// =====================================================================
// scripts/fix-sequences.js
// Sincroniza las secuencias identity a MAX(id)+1 para evitar errores
// cuando los seeds insertaron IDs explícitos que no avanzaron la
// secuencia. Uso: npm run db:fix-sequences
// =====================================================================
import 'dotenv/config'
import { getPool } from '../src/config/db.js'

async function main() {
  const pool = await getPool()
  const conn = await pool.getConnection()

  try {
    // Todas las columnas identity del esquema actual.
    const result = await conn.execute(
      `SELECT TABLE_NAME, COLUMN_NAME
         FROM ALL_TAB_IDENTITY_COLS
        WHERE OWNER = USER
        ORDER BY TABLE_NAME`,
    )

    let fixed = 0
    for (const [table, column] of result.rows) {
      try {
        // START WITH LIMIT VALUE => arranca la secuencia en MAX(id)+1.
        await conn.execute(
          `ALTER TABLE ${table} MODIFY ${column} GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)`,
        )
        console.log(`  ✔ ${table}: secuencia sincronizada a max(id)+1`)
        fixed += 1
      } catch (err) {
        // Sin filas o sin identity ajustable: se reporta pero no se aborta.
        console.log(`  ⚠ ${table}: ${err.message}`)
      }
    }
    await conn.commit()

    console.log(`\nSecuencias corregidas: ${fixed}`)
  } finally {
    await conn.close()
  }
}

main()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error('\n✖ Error al corregir secuencias:', err.message)
    process.exit(1)
  })